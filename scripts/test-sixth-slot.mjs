// Own disposable PostgreSQL instance, no inherited URL, credentials or external service.
import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import pg from 'pg';
import ts from 'typescript';
import { COMMUNITY_FETCH_LIMIT } from '../lib/community-roster.ts';
const bin = '/opt/homebrew/opt/postgresql@16/bin';
const root = await mkdtemp(join(tmpdir(),'pf-sixth-pg-'));
const data = join(root,'data');
const port = 56186;
const run = (name,args) => { const result=spawnSync(join(bin,name),args,{encoding:'utf8'}); assert.equal(result.status,0,`${name}: ${result.stderr}`); };
const client = new pg.Client({host:root,port,database:'postgres',user:'postgres'});
const other = new pg.Client({host:root,port,database:'postgres',user:'postgres'});
let started=false;
try {
  run('initdb',['-D',data,'-A','trust','-U','postgres','--no-locale']);
  run('pg_ctl',['-D',data,'-l',join(root,'server.log'),'-o',`-k ${root} -p ${port} -h ''`,'-w','start']);
  started=true;
  await client.connect(); await other.connect();
  await client.query(await readFile('db/migrations/202610120001_pump_fantasy.sql','utf8'));
  await client.query(await readFile('db/migrations/202611060004_community_players.sql','utf8'));
  await client.query(await readFile('db/migrations/202611060005_sixth_slot.sql','utf8'));
  const source = (await readFile('lib/server/community-roster.ts','utf8')).replace('import "server-only";','').replace('import { COMMUNITY_FETCH_LIMIT } from "../community-roster";',`const COMMUNITY_FETCH_LIMIT = ${COMMUNITY_FETCH_LIMIT};`);
  const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText;
  const {saveCommunityRosterSnapshot}=await import(`data:text/javascript,${encodeURIComponent(compiled)}`);
  const query=async(sql,values)=>(await client.query(sql,values)).rows;
  const wallet=n=>'1'.repeat(31)+n;
  const ranked=Array.from({length:50},(_,i)=>({id:`r${i}`,wallet:'2'.repeat(31)+'123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz'[i],rank:i+1}));
  for(const season of ['season-1','season-2','season-3']) {
    await query('insert into pf_seasons(id,title) values($1,$1)',[season]);
    for(const p of ranked) await query("insert into pf_players(id,season_id,rank,wallet,pnl_usd,source_url,snapshot_at) values($1,$2,$3,$4,0,'test',now())",[`${season}:${p.id}`,season,p.rank,p.wallet]);
  }
  const rankedWallet=ranked[0].wallet;
  const register=w=>query("insert into pf_community_players(wallet,display_name,profile_url,pnl_usd) values($1,'test','https://pump.fun/profile/test',10)",[w]);
  await register(wallet('2')); await register(rankedWallet);
  await query('begin');
  assert.equal(await saveCommunityRosterSnapshot('season-2',ranked.map(p=>p.wallet),query),1);
  await other.query("set lock_timeout='100ms'");
  await assert.rejects(other.query("insert into pf_community_players(wallet,pnl_usd) values($1,3)",[wallet('3')]),error=>error.code==='55P03');
  await query("update pf_seasons set status='open',squad_size=6 where id='season-2'");
  await query('commit');
  await register(wallet('3'));
  assert.equal((await query("select id from pf_players where season_id='season-2' and rank>50")).length,1,'late registration cannot alter the frozen roster');
  await query('begin'); await saveCommunityRosterSnapshot('season-3',ranked.map(p=>p.wallet),query); await query('commit');
  assert.equal((await query("select id from pf_players where season_id='season-3' and rank>50")).length,2,'permanent registrations enter future seasons without another burn');
  const ids=season=>[0,10,20,30,40].map(n=>`${season}:r${n}`);
  const entry=(season,picks)=>query('insert into pf_entries(season_id,wallet,picks,token_balance_raw) values($1,$2,$3,0)',[season,wallet('4'),JSON.stringify(picks)]);
  await entry('season-1',ids('season-1'));
  await assert.rejects(entry('season-2',ids('season-2')),/size/);
  const community=(await query("select id from pf_players where season_id='season-2' and rank>50"))[0].id;
  assert.equal(community,`season-2:community:${wallet('2')}`);
  await entry('season-2',[...ids('season-2'),community]);
  await assert.rejects(query("update pf_entries set picks=$1 where season_id='season-2'",[JSON.stringify([...ids('season-2').slice(0,4),'season-2:r31',community])]),/ranked bands/);
  await query("insert into pf_seasons(id,title) values('season-4','empty')");
  await query('begin');
  await assert.rejects(saveCommunityRosterSnapshot('season-4',[...ranked.map(p=>p.wallet),wallet('2'),wallet('3')],query),/No eligible community/);
  await query('rollback');
  assert.equal((await query("select status,squad_size from pf_seasons where id='season-4'"))[0].status,'draft');
  const alphabet='123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
  const capacityWallet=n=>'3'.repeat(30)+alphabet[Math.floor(n/alphabet.length)]+alphabet[n%alphabet.length];
  for(let index=0;index<98;index++) await register(capacityWallet(index));
  await query("insert into pf_seasons(id,title) values('season-5','capacity')");
  await query('begin');
  assert.equal(await saveCommunityRosterSnapshot('season-5',ranked.map(p=>p.wallet),query),100);
  await query("update pf_seasons set status='open',squad_size=6 where id='season-5'");
  await query('commit');
  assert.equal((await query("select count(*)::integer as count from pf_players where season_id='season-5' and rank>50"))[0].count,100,'capacity accepts all 100 eligible players');
  await register(capacityWallet(98));
  await query('begin');
  await query("update pf_seasons set status='open',squad_size=6 where id='season-4'");
  await assert.rejects(saveCommunityRosterSnapshot('season-4',ranked.map(p=>p.wallet),query),/scoring capacity/);
  await query('rollback');
  assert.deepEqual((await query("select status,squad_size from pf_seasons where id='season-4'"))[0],{status:'draft',squad_size:5},'101 candidates rolls back every opening write');
  assert.equal((await query("select count(*)::integer as count from pf_players where season_id='season-4'"))[0].count,0,'over-capacity does not silently trim or freeze a partial roster');
  console.log('PASS: disposable PG migration, five/six entry constraints, ranked exclusion, season-scoped IDs, registry cutoff lock, frozen/future eligibility, empty opening rollback, 100 capacity accepted, 101 capacity rollback.');
} finally {
  await client.end(); await other.end();
  if(started) run('pg_ctl',['-D',data,'-m','immediate','-w','stop']);
  await rm(root,{recursive:true,force:true});
}
